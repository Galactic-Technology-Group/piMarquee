import fs from 'node:fs/promises';
import path from 'node:path';
import YAML from 'yaml';
import type { Camera } from '@pimarquee/shared';
import type { Go2rtcClient } from './client.js';

export interface SyncLogger {
  info(msg: string): void;
  warn(msg: string): void;
}

/** Desired go2rtc stream map derived from the camera list. */
export function desiredStreams(cameras: Camera[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const c of cameras) {
    if (c.enabled) out[c.go2rtcName] = c.rtspUrl;
  }
  return out;
}

/** Merge the static template with the managed `streams:` block. */
export function renderGo2rtcYaml(template: string, streams: Record<string, string>): string {
  const doc = (YAML.parse(template) as Record<string, unknown> | null) ?? {};
  doc.streams = streams;
  return `# Generated by pimarquee. Edit go2rtc.template.yaml instead; the streams block is managed.\n${YAML.stringify(doc)}`;
}

/**
 * Keeps go2rtc in step with the camera list:
 *  1. writes the YAML so a go2rtc restart/reboot is correct, and
 *  2. reconciles the running instance through its API (no restart, no stream drop).
 */
export class Go2rtcSync {
  private retryTimer: NodeJS.Timeout | null = null;
  private pending: Record<string, string> | null = null;

  constructor(
    private readonly client: Go2rtcClient,
    private readonly templatePath: string,
    private readonly configPath: string,
    private readonly log: SyncLogger,
  ) {}

  async apply(cameras: Camera[]): Promise<void> {
    const streams = desiredStreams(cameras);
    await this.writeYaml(streams);
    await this.reconcile(streams);
  }

  private async writeYaml(streams: Record<string, string>): Promise<void> {
    if (!this.configPath) return;
    let template = 'api:\n  listen: ":1984"\n';
    try {
      template = await fs.readFile(this.templatePath, 'utf8');
    } catch {
      this.log.warn(`go2rtc template not found at ${this.templatePath}; using minimal defaults`);
    }
    const yaml = renderGo2rtcYaml(template, streams);
    await fs.mkdir(path.dirname(this.configPath), { recursive: true });
    const tmp = `${this.configPath}.tmp`;
    await fs.writeFile(tmp, yaml, 'utf8');
    await fs.rename(tmp, this.configPath);
  }

  private async reconcile(desired: Record<string, string>): Promise<void> {
    this.pending = desired;
    if (this.retryTimer) {
      clearTimeout(this.retryTimer);
      this.retryTimer = null;
    }
    try {
      const current = await this.client.listStreams();
      // go2rtc reports producer URLs; compare by name and first producer url when available.
      for (const [name, src] of Object.entries(desired)) {
        const existing = current[name];
        const existingUrl = existing?.producers?.[0]?.url;
        if (!existing || (existingUrl && existingUrl !== src)) {
          await this.client.putStream(name, src);
          this.log.info(`go2rtc: ${existing ? 'updated' : 'added'} stream ${name}`);
        }
      }
      for (const name of Object.keys(current)) {
        if (name.startsWith('cam_') && !(name in desired)) {
          await this.client.deleteStream(name);
          this.log.info(`go2rtc: removed stream ${name}`);
        }
      }
      this.pending = null;
    } catch (err) {
      this.log.warn(`go2rtc reconcile failed (${(err as Error).message}); retrying in 10s`);
      this.retryTimer = setTimeout(() => {
        if (this.pending) void this.reconcile(this.pending);
      }, 10000);
    }
  }

  stop(): void {
    if (this.retryTimer) clearTimeout(this.retryTimer);
  }
}
